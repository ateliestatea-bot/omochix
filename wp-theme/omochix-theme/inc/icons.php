<?php
/**
 * Site icons (favicon / Apple touch icon / PWA icons): ONE place, theme-owned, new infinity-mark set.
 *
 * Why theme-owned: WordPress prints its own <link rel="icon"> tags when a Site Icon is set in the Customizer, and the old
 * header also printed fallback tags - two sources, possible duplicates. Now the theme prints a single set and removes
 * WordPress's own tags. To let a Customizer Site Icon win again:
 *     add_filter('omochix_theme_icons_override_site_icon', '__return_false');
 * (the theme then prints nothing while a Site Icon exists, as before).
 * Files: assets/img/icons/ (generated by tools/icons/build-favicons.cjs from the brand mark; see docs/nav-ux-update/).
 */
if (!defined('ABSPATH')) { exit; }

function omochix_icons_override_site_icon() { return (bool) apply_filters('omochix_theme_icons_override_site_icon', true); }
function omochix_icon_uri($file) { return get_theme_file_uri('/assets/img/icons/' . $file); }

function omochix_icon_links() {
    if (!omochix_icons_override_site_icon() && function_exists('has_site_icon') && has_site_icon()) { return; }
    $tags = [
        ['rel' => 'icon', 'href' => omochix_icon_uri('favicon.ico'), 'sizes' => '48x48'],
        ['rel' => 'icon', 'href' => omochix_icon_uri('favicon.svg'), 'type' => 'image/svg+xml', 'sizes' => 'any'],
        ['rel' => 'icon', 'href' => omochix_icon_uri('favicon-32.png'), 'type' => 'image/png', 'sizes' => '32x32'],
        ['rel' => 'icon', 'href' => omochix_icon_uri('favicon-16.png'), 'type' => 'image/png', 'sizes' => '16x16'],
        ['rel' => 'apple-touch-icon', 'href' => omochix_icon_uri('apple-touch-icon-180.png'), 'sizes' => '180x180'],
    ];
    foreach ($tags as $t) {
        $attrs = '';
        foreach ($t as $k => $v) { $attrs .= ' ' . $k . '="' . esc_attr('href' === $k ? esc_url($v) : $v) . '"'; }
        echo '<link' . $attrs . ">\n"; // phpcs:ignore WordPress.Security.EscapeOutput -- built from escaped parts
    }
}

// Remove WordPress's own site-icon tags so there is exactly one set of icon links.
add_filter('site_icon_meta_tags', static function ($tags) {
    // Only the public front end uses the theme icon set; wp-admin and wp-login.php keep WordPress's Site Icon tags (F1).
    if (is_admin() || did_action('login_init')) {
        return $tags;
    }
    return omochix_icons_override_site_icon() ? [] : $tags;
});

// /favicon.ico requested without a <link>: serve the theme icon instead of WordPress's default or the old Site Icon.
add_action('do_faviconico', static function () {
    if (!omochix_icons_override_site_icon()) { return; }
    $file = get_theme_file_path('/assets/img/icons/favicon.ico');
    if (!is_readable($file)) { return; }
    header('Content-Type: image/vnd.microsoft.icon');
    header('Cache-Control: public, max-age=86400');
    readfile($file);
    exit;
});
